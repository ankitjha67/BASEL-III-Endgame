"""GIRR regulatory parameters -- US ERBA NPR (March 2026) §__.208-§__.209.

All risk weights, correlations, and regulatory constants for the General
Interest Rate Risk (GIRR) class under the FRTB Sensitivities-Based Method as
written in the March 2026 Federal Reserve re-proposal, 12 CFR 217 Subpart F:

* §__.208(b)   -- GIRR risk factors (ten delta vertices, inflation, cross-
                  currency basis, vega grid, curvature parallel shift).
* §__.209(b)(1) -- GIRR delta risk weights (Table 1), tenor correlation
                  matrix (Table 2), cross-curve / inflation / basis
                  correlations and the inter-bucket correlation.
* §__.209 Table 11 and the vega / curvature paragraphs -- vega risk weight
  and the curvature correlation parameters.

The US text governs wherever it differs from BCBS d457 MAR21; the MAR21
paragraph is given only as a cross-reference.
"""
from __future__ import annotations

import math

from src.core.enums import CorrelationScenario, CurrencyCategory

# ---------------------------------------------------------------------------
# Standard delta tenor vertices (years) -- ERBA NPR §__.208(b)(1)
# (BCBS d457 MAR21.8(1)).  Exactly ten vertices.
# ---------------------------------------------------------------------------
TENORS: list[float] = [0.25, 0.5, 1.0, 2.0, 3.0, 5.0, 10.0, 15.0, 20.0, 30.0]

# ---------------------------------------------------------------------------
# Delta risk weights -- ERBA NPR §__.209(b)(1) Table 1 (BCBS MAR21.42)
# These are the BASE risk weights that apply to every currency.  Specified
# currencies (see SPECIFIED_CURRENCIES) MAY divide them by sqrt(2).
# ---------------------------------------------------------------------------
DELTA_RISK_WEIGHTS: dict[float, float] = {
    0.25: 0.017,  # 1.7%
    0.5:  0.017,  # 1.7%
    1.0:  0.016,  # 1.6%
    2.0:  0.013,  # 1.3%
    3.0:  0.012,  # 1.2%
    5.0:  0.011,  # 1.1%
    10.0: 0.011,  # 1.1%
    15.0: 0.011,  # 1.1%
    20.0: 0.011,  # 1.1%
    30.0: 0.011,  # 1.1%
}

# ---------------------------------------------------------------------------
# Inflation and cross-currency basis risk weights -- ERBA NPR §__.209(b)(1)
# ---------------------------------------------------------------------------
RW_INFLATION: float = 0.016  # 1.6%
RW_XCCY_BASIS: float = 0.016  # 1.6%

# ---------------------------------------------------------------------------
# Specified currencies -- ERBA NPR §__.209(b)(1)
# "USD, AUD, CAD, EUR, JPY, SEK, GBP, and any other currency specified by
# the [agency]" may have their Table 1 risk weights divided by sqrt(2).
# NOTE: CHF is NOT on the US list (it is on the BCBS MAR21.43 list).
# ---------------------------------------------------------------------------
SPECIFIED_CURRENCIES: set[str] = {
    "USD", "AUD", "CAD", "EUR", "JPY", "SEK", "GBP",
}

# Divisor applied to Table 1 risk weights for specified currencies
# (ERBA NPR §__.209(b)(1): "may divide the risk weights by the square root
# of 2").
SPECIFIED_CURRENCY_RW_DIVISOR: float = math.sqrt(2)  # ~1.4142

# ---------------------------------------------------------------------------
# Intra-bucket tenor correlation parameters -- ERBA NPR §__.209(b)(1)
# Table 2 is generated by  max(exp(-THETA * |T_k - T_l| / min(T_k, T_l)), 40%)
# (BCBS MAR21.45).
# ---------------------------------------------------------------------------
THETA: float = 0.03  # Correlation decay parameter
CORRELATION_FLOOR: float = 0.40  # Minimum tenor correlation

# ---------------------------------------------------------------------------
# Cross-curve / inflation / basis correlations within a bucket
# ERBA NPR §__.209(b)(1) (BCBS MAR21.46-21.49)
# ---------------------------------------------------------------------------
RHO_CROSS_CURVE: float = 0.999       # Same tenor, different yield curves (99.9%)
RHO_INFLATION: float = 0.40          # Inflation vs yield curve (40%)
RHO_INFLATION_CROSS_CURVE: float = 0.999  # Two inflation curves, same currency (99.9%)
RHO_XCCY_BASIS: float = 0.00         # Cross-currency basis vs everything (0%)
RHO_INFLATION_XCCY: float = 0.00     # Inflation vs cross-currency basis (0%)

# ---------------------------------------------------------------------------
# Inter-bucket correlation -- ERBA NPR §__.209(b)(1) (BCBS MAR21.50)
# ---------------------------------------------------------------------------
GAMMA_GIRR: float = 0.50  # 50% between all currency buckets

# ---------------------------------------------------------------------------
# Vega parameters -- ERBA NPR §__.208(b)(2), §__.209 Table 11 (BCBS MAR21.92-93)
# ---------------------------------------------------------------------------
VEGA_RISK_WEIGHT: float = 1.0  # 100% (Table 11, GIRR)
VEGA_LIQUIDITY_HORIZON: int = 60  # Business days (informational; RW capped at 100%)
VEGA_OPTION_MATURITIES: list[float] = [0.5, 1.0, 3.0, 5.0, 10.0]
VEGA_UNDERLYING_TENORS: list[float] = [0.5, 1.0, 3.0, 5.0, 10.0]
VEGA_ALPHA: float = 0.01  # alpha = 1% in exp(-alpha * |T_k - T_l| / min(T_k, T_l))

# ---------------------------------------------------------------------------
# Curvature parameters -- ERBA NPR §__.208(b)(3) and §__.209 curvature
# paragraph (BCBS MAR21.98, MAR21.101).
#   * Shock: parallel shift of all vertices of a curve by the HIGHEST delta
#     risk weight of the bucket (1.7%, or 1.7%/sqrt(2) for specified
#     currencies).  No curvature for inflation or cross-currency basis.
#   * Intra-bucket correlation: 100% within a curve (parallel shift = one
#     risk factor per curve), 99.8% between different curves.
#   * Inter-bucket correlation: GAMMA_GIRR squared.
# ---------------------------------------------------------------------------
RHO_CURVATURE_SAME_CURVE: float = 1.0
RHO_CURVATURE_CROSS_CURVE: float = 0.998  # 99.8% (= 99.9% squared, as stated in the NPR)


# ---------------------------------------------------------------------------
# Helper functions
# ---------------------------------------------------------------------------


def is_specified_currency(currency: str) -> bool:
    """Return whether *currency* is on the ERBA NPR §__.209(b)(1) specified list.

    Args:
        currency: ISO 4217 currency code (case-insensitive).

    Returns:
        ``True`` for USD, AUD, CAD, EUR, JPY, SEK and GBP; ``False`` otherwise.
    """
    return currency.upper() in SPECIFIED_CURRENCIES


def get_currency_category(currency: str) -> CurrencyCategory:
    """Classify a currency for GIRR delta risk-weight purposes.

    ERBA NPR §__.209(b)(1): specified currencies may divide the Table 1
    risk weights by sqrt(2); every other currency uses Table 1 unchanged.

    Args:
        currency: ISO 4217 currency code (e.g. ``"USD"``).

    Returns:
        ``CurrencyCategory.SPECIFIED`` for the seven specified currencies,
        otherwise ``CurrencyCategory.OTHER``.
    """
    if is_specified_currency(currency):
        return CurrencyCategory.SPECIFIED
    return CurrencyCategory.OTHER


def get_delta_risk_weight(tenor: float, currency: str) -> float:
    """Get the GIRR delta risk weight for a tenor vertex and currency.

    ERBA NPR §__.209(b)(1) Table 1 gives the base risk weight per vertex.
    For specified currencies (USD, AUD, CAD, EUR, JPY, SEK, GBP) the base
    weight is DIVIDED by sqrt(2); all other currencies use the base weight.
    Example: 0.25y USD = 1.7%/sqrt(2) = 1.202%; 0.25y BRL = 1.7%.

    Args:
        tenor: Tenor vertex in years (must be one of :data:`TENORS`).
        currency: ISO 4217 currency code.

    Returns:
        Risk weight as a decimal (e.g. 0.017 for 1.7%).

    Raises:
        KeyError: If *tenor* is not one of the ten prescribed vertices.
    """
    base_rw = DELTA_RISK_WEIGHTS[tenor]
    if get_currency_category(currency) == CurrencyCategory.SPECIFIED:
        return base_rw / SPECIFIED_CURRENCY_RW_DIVISOR
    return base_rw


def get_curvature_risk_weight(currency: str) -> float:
    """Get the GIRR curvature shock size for a currency bucket.

    ERBA NPR §__.208(b)(3) / §__.209 curvature paragraph: the curvature
    risk weight is a parallel shift of every vertex of the curve by the
    highest delta risk weight prescribed for the bucket, i.e. 1.7% (or
    1.7%/sqrt(2) for specified currencies).  Inflation and cross-currency
    basis risk factors carry no curvature requirement.

    Args:
        currency: ISO 4217 currency code of the bucket.

    Returns:
        Curvature shock as a decimal.
    """
    highest_rw = max(DELTA_RISK_WEIGHTS.values())
    if get_currency_category(currency) == CurrencyCategory.SPECIFIED:
        return highest_rw / SPECIFIED_CURRENCY_RW_DIVISOR
    return highest_rw


def compute_tenor_correlation(tenor_k: float, tenor_l: float) -> float:
    """Compute the same-curve tenor correlation per ERBA NPR §__.209(b)(1).

    Reproduces Table 2 of §__.209(b)(1) (BCBS MAR21.45):

    .. math::

        \\rho(k, l) = \\max\\!\\bigl(
            e^{-\\theta \\,|T_k - T_l| / \\min(T_k, T_l)},\\;
            40\\%
        \\bigr),\\quad \\theta = 3\\%

    e.g. 0.25y-0.5y = 97.0%, 0.25y-1y = 91.4%, 0.25y-30y = 40.0%.

    Args:
        tenor_k: First tenor vertex in years.
        tenor_l: Second tenor vertex in years.

    Returns:
        Correlation between the two tenor vertices, floored at
        :data:`CORRELATION_FLOOR`.
    """
    if tenor_k == tenor_l:
        return 1.0
    ratio = abs(tenor_k - tenor_l) / min(tenor_k, tenor_l)
    raw = math.exp(-THETA * ratio)
    return max(raw, CORRELATION_FLOOR)


def compute_vega_maturity_correlation(maturity_k: float, maturity_l: float) -> float:
    """One-dimensional vega maturity correlation per ERBA NPR §__.209 (vega).

    ``exp(-alpha * |T_k - T_l| / min(T_k, T_l))`` with ``alpha = 1%``
    (BCBS MAR21.93).  Applied once to the option maturities and once to the
    underlying residual maturities; the GIRR vega correlation is
    ``min(rho_option * rho_underlying, 1)``.

    Args:
        maturity_k: First maturity in years.
        maturity_l: Second maturity in years.

    Returns:
        Correlation in (0, 1].
    """
    if maturity_k == maturity_l:
        return 1.0
    return math.exp(-VEGA_ALPHA * abs(maturity_k - maturity_l) / min(maturity_k, maturity_l))


def apply_correlation_scenario(
    rho: float,
    scenario: CorrelationScenario,
    is_inter_bucket: bool = False,
) -> float:
    """Apply the correlation scenario adjustment per ERBA NPR §__.206(c).

    +---------+--------------------------------------+
    | Scenario| Adjusted correlation                 |
    +=========+======================================+
    | LOW     | ``max(2*rho - 1, 0.75*rho)``         |
    +---------+--------------------------------------+
    | MEDIUM  | ``rho`` (no change)                  |
    +---------+--------------------------------------+
    | HIGH    | ``min(1.0, 1.25*rho)``               |
    +---------+--------------------------------------+

    (BCBS MAR21.6.)

    Args:
        rho: Base correlation value.
        scenario: One of LOW / MEDIUM / HIGH.
        is_inter_bucket: Whether this is an inter-bucket correlation
            (reserved for future use with differentiated scaling).

    Returns:
        Scenario-adjusted correlation.
    """
    if scenario == CorrelationScenario.MEDIUM:
        return rho
    elif scenario == CorrelationScenario.HIGH:
        return min(1.0, 1.25 * rho)
    else:  # LOW
        return max(2 * rho - 1, 0.75 * rho)


def build_girr_correlation_matrix(
    currency: str,
    num_yield_curve_sensitivities: int,
    curve_labels: list[str],
    tenors: list[float],
    include_inflation: bool = False,
    include_xccy_basis: bool = False,
    scenario: CorrelationScenario = CorrelationScenario.MEDIUM,
    inflation_labels: list[str] | None = None,
    xccy_basis_labels: list[str] | None = None,
) -> "numpy.ndarray":
    """Build the full intra-bucket delta correlation matrix for a GIRR bucket.

    Matrix dimensions::

        n_yield_curve + n_inflation + n_xccy_basis

    Correlation rules per ERBA NPR §__.209(b)(1):

    * **Yield curve, same curve, different tenors:** ``rho_tenor(k, l)``
      (Table 2).
    * **Yield curve, different curves, same tenor:** 99.9%.
    * **Yield curve, different curves, different tenors:**
      ``rho_tenor(k, l) * 99.9%``.
    * **Yield curve to inflation:** 40%.
    * **Inflation to inflation (different curves):** 99.9%.
    * **Cross-currency basis to anything else:** 0%.

    Args:
        currency: ISO 4217 currency code for the bucket.
        num_yield_curve_sensitivities: Number of yield-curve risk factor
            entries (curve x tenor combinations).
        curve_labels: Label for each yield-curve sensitivity indicating
            which curve it belongs to (length must equal
            *num_yield_curve_sensitivities*).
        tenors: Tenor (in years) for each yield-curve sensitivity (length
            must equal *num_yield_curve_sensitivities*).
        include_inflation: Add a single inflation row/column (ignored when
            *inflation_labels* is given).
        include_xccy_basis: Add a single cross-currency basis row/column
            (ignored when *xccy_basis_labels* is given).
        scenario: Correlation scenario to apply (LOW / MEDIUM / HIGH).
        inflation_labels: One label per inflation sensitivity; identical
            labels are the same inflation curve (correlation 100%).
        xccy_basis_labels: One label per cross-currency basis sensitivity;
            identical labels are the same basis curve (correlation 100%).

    Returns:
        A symmetric ``numpy.ndarray`` of shape ``(total, total)`` containing
        the scenario-adjusted correlation matrix, ordered yield-curve rows,
        then inflation rows, then cross-currency basis rows.
    """
    import numpy as np  # noqa: WPS433 (local import to keep module lightweight)

    n = num_yield_curve_sensitivities
    if inflation_labels is None:
        inflation_labels = ["INFLATION"] if include_inflation else []
    if xccy_basis_labels is None:
        xccy_basis_labels = ["XCCY"] if include_xccy_basis else []

    n_infl = len(inflation_labels)
    n_xccy = len(xccy_basis_labels)
    total = n + n_infl + n_xccy

    corr = np.eye(total)

    # --- Yield curve correlations -------------------------------------------
    for i in range(n):
        for j in range(i + 1, n):
            rho = compute_tenor_correlation(tenors[i], tenors[j])
            if curve_labels[i] != curve_labels[j]:
                rho *= RHO_CROSS_CURVE
            rho = apply_correlation_scenario(rho, scenario)
            corr[i, j] = rho
            corr[j, i] = rho

    # --- Inflation correlations ---------------------------------------------
    for a in range(n_infl):
        ia = n + a
        # Inflation vs every yield-curve factor: 40%
        for i in range(n):
            rho = apply_correlation_scenario(RHO_INFLATION, scenario)
            corr[i, ia] = rho
            corr[ia, i] = rho
        # Inflation vs other inflation curves: 99.9% (same curve = 100%)
        for b in range(a + 1, n_infl):
            ib = n + b
            base = (
                1.0
                if inflation_labels[a] == inflation_labels[b]
                else RHO_INFLATION_CROSS_CURVE
            )
            rho = apply_correlation_scenario(base, scenario)
            corr[ia, ib] = rho
            corr[ib, ia] = rho

    # --- Cross-currency basis correlations (0% with everything) --------------
    # RHO_XCCY_BASIS / RHO_INFLATION_XCCY are both 0, which np.eye already
    # provides.  Two sensitivities on the SAME basis curve are one risk
    # factor and correlate at 100%.
    offset = n + n_infl
    for a in range(n_xccy):
        ia = offset + a
        for b in range(a + 1, n_xccy):
            ib = offset + b
            base = 1.0 if xccy_basis_labels[a] == xccy_basis_labels[b] else RHO_XCCY_BASIS
            rho = apply_correlation_scenario(base, scenario)
            corr[ia, ib] = rho
            corr[ib, ia] = rho

    return corr


def build_girr_curvature_correlation_matrix(
    curve_labels: list[str],
    scenario: CorrelationScenario = CorrelationScenario.MEDIUM,
) -> "numpy.ndarray":
    """Build the intra-bucket curvature correlation matrix for a GIRR bucket.

    ERBA NPR §__.209 (curvature): because the GIRR curvature shock is a
    parallel shift of the whole curve, each yield curve is a single
    curvature risk factor.  The correlation is 100% between curvature
    positions on the same curve and 99.8% between different curves in the
    same currency.  (This is the only risk class for which the NPR states
    the curvature correlation directly rather than as the delta correlation
    squared.)

    Args:
        curve_labels: Curve label for each curvature position.
        scenario: Correlation scenario to apply.

    Returns:
        Symmetric ``numpy.ndarray`` of shape ``(len(curve_labels),) * 2``.
    """
    import numpy as np  # noqa: WPS433

    n = len(curve_labels)
    corr = np.eye(n)
    for i in range(n):
        for j in range(i + 1, n):
            base = (
                RHO_CURVATURE_SAME_CURVE
                if curve_labels[i] == curve_labels[j]
                else RHO_CURVATURE_CROSS_CURVE
            )
            rho = apply_correlation_scenario(base, scenario)
            corr[i, j] = rho
            corr[j, i] = rho
    return corr
